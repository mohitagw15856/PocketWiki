def encode_glyph(art):
    """Encode a 7 row by 5 column glyph as 5 column major bytes.

    Bit 0 of each byte is the top row, bit 6 is the bottom row.
    """
    assert len(art) == HEIGHT, "glyph must have %d rows" % HEIGHT
    for row in art:
        assert len(row) == WIDTH, "row must be %d columns wide: %r" % (WIDTH, row)
    columns = []
    for x in range(WIDTH):
        byte = 0
        for r in range(HEIGHT):
            pixel = art[r][x]
            if pixel == '#':
                byte |= (1 << r)
        columns.append(byte)
    return columns


def char_comment(c):
    """Return a printable single quoted representation for the trailing comment."""
    if c == "'":
        return "'\\''"
    if c == "\\":
        return "'\\\\'"
    return "'%s'" % c


def main():
    # Sanity check: all 95 characters present.
    expected = [chr(code) for code in range(FIRST, LAST + 1)]
    missing = [c for c in expected if c not in GLYPHS]
    if missing:
        raise SystemExit("Missing glyphs for: %r" % missing)
    count = len(expected)

    out_path = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "core", "pocketwiki", "Font5x7.h",
    )

    lines = []
    lines.append(
        "// 5x7 bitmap font for printable ASCII (0x20..0x7E). Generated by tools/genfont.py.")
    lines.append(
        "// Do not edit by hand; edit the glyph art in tools/genfont.py and regenerate.")
    lines.append("//")
    lines.append(
        "// Column major: each glyph is kFontWidth bytes, one per column left to right;")
    lines.append(
        "// within a column bit 0 is the top row and bit 6 is the bottom row.")
    lines.append("// Arduino free so it compiles in the host build.")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append("namespace pocketwiki {")
    lines.append("")
    lines.append("constexpr int kFontWidth = 5;")
    lines.append("constexpr int kFontHeight = 7;")
    lines.append("constexpr int kFontFirst = 0x20;")
    lines.append("constexpr int kFontLast = 0x7E;")
    lines.append("")
    lines.append("// 5 column bytes for each glyph, indexed [c - kFontFirst].")
    lines.append(
        "inline constexpr uint8_t kFont5x7[(kFontLast - kFontFirst + 1)][kFontWidth] = {")
    for code in range(FIRST, LAST + 1):
        c = chr(code)
        cols = encode_glyph(GLYPHS[c])
        byte_text = ",".join("0x%02X" % b for b in cols)
        lines.append(
            "    {%s}, // 0x%02X %s" % (byte_text, code, char_comment(c)))
    lines.append("};")
    lines.append("")
    lines.append(
        "// Return the 5 column bytes for character c, falling back to '?' for anything")
    lines.append("// outside the printable range.")
    lines.append("inline const uint8_t* font5x7Columns(char c) {")
    lines.append("  unsigned uc = static_cast<unsigned char>(c);")
    lines.append(
        "  if (uc < static_cast<unsigned>(kFontFirst) || uc > static_cast<unsigned>(kFontLast)) {")
    lines.append("    uc = static_cast<unsigned>('?');")
    lines.append("  }")
    lines.append("  return kFont5x7[uc - kFontFirst];")
    lines.append("}")
    lines.append("")
    lines.append("}  // namespace pocketwiki")
    lines.append("")

    with open(out_path, "w") as f:
        f.write("\n".join(lines))

    print("Wrote %s" % out_path)
    print("Encoded %d glyphs." % count)


if __name__ == "__main__":
    main()
